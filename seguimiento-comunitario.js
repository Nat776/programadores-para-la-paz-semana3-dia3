let semanaActual = 1
const semanasDeSeguimiento = 4
let propuestasAtendidas = 3

console.log("Seguimiento comunitario del programa")

while (semanaActual <= semanasDeSeguimiento) {
  console.log("Semana", semanaActual, "- Propuestas atendidas:", propuestasAtendidas)
  semanaActual = semanaActual + 1
}

console.log("Proceso de seguimiento comunitario finalizado.")
